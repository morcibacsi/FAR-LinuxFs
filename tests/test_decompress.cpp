{
    const auto text = TextPattern();
    const auto binary = BinaryPattern();
    Check("stored", stored, text);
    Check("fixed Huffman", fixedHuffman, text);
    Check("dynamic Huffman", dynamicHuffman, text);
    Check("binary", binaryDeflate, binary);
    CheckCorruptInputIsRejected();
    CheckLzo();
    return failures != 0 ? 1 : 0;
}
