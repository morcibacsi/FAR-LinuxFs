    std::vector<u8> TextPattern()
    {
        std::string text;
        for (int i = 0; text.size() < 4096; ++i)
            text += "line " + std::to_string(i * 7 % 13) + " of the sample data, with some repetition repetition\n";
        text.resize(4096);
        return std::vector<u8>(text.begin(), text.end());
    }

    std::vector<u8> BinaryPattern()
    {
        std::vector<u8> data(1024);
        for (unsigned i = 0; i != data.size(); ++i)
            data[i] = static_cast<u8>(i * i);
        return data;
    }

    int failures = 0;

    template <size_t N>
    void Check(const char* name, const unsigned char (&input)[N], const std::vector<u8>& expected)
    {
        std::vector<u8> output(expected.size());
        bool ok = false;
        try
        {
            ok = InflateRaw(input, N, output.data(), output.size()) == expected.size() && output == expected;
        }
        catch (const FsError& error)
        {
            std::printf("%s: %s\n", name, error.what());
        }
        std::printf("%s: %s\n", name, ok ? "ok" : "FAILED");
        failures += ok ? 0 : 1;
    }

    void CheckCorruptInputIsRejected()
    {
        std::vector<u8> truncated(dynamicHuffman, dynamicHuffman + sizeof dynamicHuffman / 2);
        std::vector<u8> output(4096);
        bool rejected = false;
        try
        {
            InflateRaw(truncated.data(), truncated.size(), output.data(), output.size());
        }
        catch (const FsError&)
        {
            rejected = true;
        }
        std::printf("truncated input: %s\n", rejected ? "ok" : "FAILED");
        failures += rejected ? 0 : 1;
    }

    void CheckLzo()
    {
        // Literals "abc", then a match of length 6 at distance 3, then the end marker.
        const u8 input[] = { 17 + 3, 'a', 'b', 'c', (6 - 2) | 32, 2 << 2, 0, 17, 0, 0 };
        u8 output[16];
        bool ok = false;
        try
        {
            ok = Lzo1xDecompress(input, sizeof input, output, sizeof output) == 9 && std::memcmp(output, "abcabcabc", 9) == 0;
        }
        catch (const FsError& error)
        {
            std::printf("lzo: %s\n", error.what());
        }
        std::printf("lzo: %s\n", ok ? "ok" : "FAILED");
        failures += ok ? 0 : 1;
    }
